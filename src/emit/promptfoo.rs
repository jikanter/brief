//! promptfoo providers that replay the brief's astrophage cassette sets.
//!
//! astrophage is a record/replay gateway for OpenAI-compatible clients. A
//! client reaches it through one base URL, and picks the policy and the set
//! with two request headers (`x-aichat-cache-mode`, `x-aichat-cassette`), which
//! override the gateway's launch defaults. So each bound set becomes one
//! promptfoo `openai:chat` provider that points at the gateway and sends those
//! headers. One running gateway then serves every set.
//!
//! The output is a bare YAML list, the shape promptfoo loads from
//! `providers: [file://...]`. Brief prints it and stops: it does not start the
//! gateway, run promptfoo, or make any request.

use crate::emit::yaml::yaml_scalar;
use crate::fixtures::{cassette_bindings, invalid_set_name_message, is_valid_set_name};
use crate::model::Brief;

/// Where `astrophage serve` listens by default (`--listen 127.0.0.1:8080`),
/// plus the `/v1` prefix promptfoo's OpenAI provider expects on a base URL.
pub const ASTROPHAGE_BASE_URL: &str = "http://127.0.0.1:8080/v1";

const HEADER: &str = "\
# promptfoo providers that replay astrophage cassette sets.
# Generated by `brief emit promptfoo`: edit the brief, not this file.
#
# Save it and load it from promptfooconfig.yaml:
#   brief emit promptfoo > brief-providers.yaml
#   providers:
#     - file://brief-providers.yaml
#
# Start the gateway before `promptfoo eval`. It replays offline and fails any
# request the cassette does not hold, so no call reaches a live provider:
#   astrophage serve --mode cassette --cassettes-dir cassettes
";

/// Why the brief cannot be emitted as promptfoo providers, if it cannot: it
/// binds no cassette, names no model, or binds a set name that is not a plain
/// directory name.
pub fn promptfoo_preflight(brief: &Brief) -> Result<(), String> {
    let bindings = cassette_bindings(brief);
    if bindings.is_empty() {
        return Err(
            "no cassette binding to emit: add `cassettes: [<set>]` to the \
                    frontmatter or a `- cassette: <set> — <reason>` item under `## Fixtures`"
                .to_string(),
        );
    }
    if let Some(bad) = bindings.iter().find(|b| !is_valid_set_name(&b.name)) {
        return Err(invalid_set_name_message(&bad.name));
    }
    if brief.frontmatter.model.is_none() {
        return Err("the promptfoo target needs a `model` in the frontmatter: \
                    the model is part of every recorded request, so a replay \
                    must send the one the cassette was recorded with"
            .to_string());
    }
    Ok(())
}

/// Render one promptfoo provider per bound cassette set. Call
/// [`promptfoo_preflight`] first: this assumes a model and valid set names.
pub fn emit_promptfoo(brief: &Brief) -> String {
    let model = brief.frontmatter.model.as_deref().unwrap_or_default();
    let id = yaml_scalar(&format!("openai:chat:{model}"));
    let base_url = yaml_scalar(ASTROPHAGE_BASE_URL);

    let mut out = String::from(HEADER);
    for binding in cassette_bindings(brief) {
        let set = yaml_scalar(&binding.name);
        out.push('\n');
        if let Some(reason) = &binding.reason {
            out.push_str(&format!("# {}\n", reason.replace('\n', " ")));
        }
        out.push_str(&format!(
            "- id: {id}\n  label: {set}\n  config:\n    apiBaseUrl: {base_url}\n    \
             apiKeyRequired: false\n    headers:\n      x-aichat-cache-mode: cassette\n      \
             x-aichat-cassette: {set}\n"
        ));
    }
    out
}
